  COALESCE(
    NULLIF(au.raw_user_meta_data->>'full_name',''),
    NULLIF(s.full_name,''),
    NULLIF(st.full_name,''),
    split_part(COALESCE(au.email,''),'@',1)
  ) AS full_name,
  au.email,
  COALESCE(st.phone, s.guardian_phone) AS phone,
  ur.role::text AS role
